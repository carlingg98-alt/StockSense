const express = require('express');
const mongoose = require('mongoose');
const PurchaseOrder = require('../models/PurchaseOrder');
const Supplier = require('../models/Supplier');
const Product = require('../models/Product');
const HttpError = require('../utils/HttpError');
const validateObjectId = require('../middleware/validateObjectId');
const { recordTransaction } = require('../services/stockService');
const { DAY_MS } = require('../services/dateUtils');

const router = express.Router();
// REQUIREMENT [Core Req 2 - REST API]: invalid :id values are rejected with 400.
router.param('id', validateObjectId);

const POPULATE = [
  { path: 'supplier', select: 'name contactPerson phone leadTimeDays' },
  { path: 'items.product', select: 'name sku unit quantity' },
];

// REQUIREMENT [Data Processing and Business Logic]: status transitions with rules - a state table. draft -> ordered -> received, cancel only before received; "received" and "cancelled" are final.
// Which status changes are allowed. "received" and "cancelled" are final.
const ALLOWED_MOVES = {
  draft: ['ordered', 'cancelled'],
  ordered: ['received', 'cancelled'],
  received: [],
  cancelled: [],
};

// Next number in the PO-0001, PO-0002, ... sequence
// REQUIREMENT [Data Processing and Business Logic]: generates the next order number (PO-0001, PO-0002, ...).
async function nextOrderNumber() {
  const orders = await PurchaseOrder.find().select('orderNumber').lean();
  let highest = 0;
  for (const order of orders) {
    const n = parseInt(String(order.orderNumber).replace('PO-', ''), 10);
    if (!Number.isNaN(n) && n > highest) highest = n;
  }
  return `PO-${String(highest + 1).padStart(4, '0')}`;
}

// Check supplier and items, and make sure every product belongs to that supplier.
// REQUIREMENT [Data Processing and Business Logic]: server-side validation of an order - active supplier, at least one item, no duplicate product, and every product must belong to the chosen supplier.
async function validateOrderBody(body) {
  const { supplier, items } = body;

  if (!supplier || !mongoose.isValidObjectId(supplier)) throw new HttpError(400, 'Supplier is required');
  const supplierDoc = await Supplier.findById(supplier);
  if (!supplierDoc) throw new HttpError(400, 'Selected supplier does not exist');
  if (!supplierDoc.isActive) throw new HttpError(400, `${supplierDoc.name} is marked inactive`);

  if (!Array.isArray(items) || items.length === 0) {
    throw new HttpError(400, 'A purchase order needs at least one item');
  }

  const seen = new Set();
  for (const item of items) {
    if (!item || !mongoose.isValidObjectId(item.product)) {
      throw new HttpError(400, 'Each item needs a valid product');
    }
    if (seen.has(String(item.product))) {
      throw new HttpError(400, 'The same product appears twice. Combine it into one line.');
    }
    seen.add(String(item.product));

    const product = await Product.findById(item.product);
    if (!product) throw new HttpError(400, 'One of the products does not exist');
    if (String(product.supplier) !== String(supplierDoc._id)) {
      throw new HttpError(400, `${product.name} is not supplied by ${supplierDoc.name}`);
    }
  }
}

// REQUIREMENT [Core Req 2 - REST API]: list all (200) with optional status filter. An unknown status is a 400.
// GET /api/purchase-orders?status=
router.get('/', async (req, res) => {
  const filter = {};
  if (req.query.status) {
    if (!PurchaseOrder.STATUSES.includes(req.query.status)) {
      throw new HttpError(400, `status must be one of: ${PurchaseOrder.STATUSES.join(', ')}`);
    }
    filter.status = req.query.status;
  }
  const orders = await PurchaseOrder.find(filter).populate(POPULATE).sort({ createdAt: -1 });
  res.status(200).json(orders);
});

// REQUIREMENT [Core Req 2 - REST API]: get one (200 / 404).
// GET /api/purchase-orders/:id
router.get('/:id', async (req, res) => {
  const order = await PurchaseOrder.findById(req.params.id).populate(POPULATE);
  if (!order) throw new HttpError(404, 'Purchase order not found');
  res.status(200).json(order);
});

// REQUIREMENT [Core Req 2 - REST API]: create (201). Starts as draft; the order number is generated by the server.
// POST /api/purchase-orders - always starts as a draft
router.post('/', async (req, res) => {
  await validateOrderBody(req.body);

  const order = await PurchaseOrder.create({
    orderNumber: await nextOrderNumber(),
    supplier: req.body.supplier,
    items: req.body.items.map((i) => ({ product: i.product, quantity: i.quantity, unitCost: i.unitCost })),
    note: req.body.note,
  });

  await order.populate(POPULATE);
  res.status(201).json(order);
});

// REQUIREMENT [Data Processing and Business Logic]: update (200) - only DRAFT orders can be edited, otherwise 400.
// PUT /api/purchase-orders/:id - only drafts can be edited
router.put('/:id', async (req, res) => {
  const order = await PurchaseOrder.findById(req.params.id);
  if (!order) throw new HttpError(404, 'Purchase order not found');
  if (order.status !== 'draft') {
    throw new HttpError(400, `Only draft orders can be edited. This order is ${order.status}.`);
  }

  await validateOrderBody(req.body);
  order.supplier = req.body.supplier;
  order.items = req.body.items.map((i) => ({ product: i.product, quantity: i.quantity, unitCost: i.unitCost }));
  if (req.body.note !== undefined) order.note = req.body.note;
  await order.save();

  await order.populate(POPULATE);
  res.status(200).json(order);
});

// REQUIREMENT [Data Processing and Business Logic] (Processing endpoint 8): rule-based status change. Checked against ALLOWED_MOVES, otherwise 400 with a clear message.
// PATCH /api/purchase-orders/:id/status - rule-based status change
// Body: { "status": "ordered" | "received" | "cancelled" }
router.patch('/:id/status', async (req, res) => {
  const next = req.body.status;
  if (!PurchaseOrder.STATUSES.includes(next)) {
    throw new HttpError(400, `status must be one of: ${PurchaseOrder.STATUSES.join(', ')}`);
  }

  const order = await PurchaseOrder.findById(req.params.id).populate('supplier');
  if (!order) throw new HttpError(404, 'Purchase order not found');

  if (!ALLOWED_MOVES[order.status].includes(next)) {
    const allowed = ALLOWED_MOVES[order.status];
    throw new HttpError(
      400,
      allowed.length === 0
        ? `This order is already ${order.status} and can no longer change`
        : `A ${order.status} order can only become: ${allowed.join(' or ')}`
    );
  }

  // REQUIREMENT [Data Processing and Business Logic]: date logic - expected delivery date = today + supplier lead time.
  if (next === 'ordered') {
    // Expected delivery = today + the supplier's lead time
    order.orderedAt = new Date();
    const leadTime = order.supplier ? order.supplier.leadTimeDays : 0;
    order.expectedDate = new Date(Date.now() + leadTime * DAY_MS);
  }

  // REQUIREMENT [Data Processing and Business Logic]: receiving creates a restock transaction for every item (stock goes up, unit cost is updated). All items are checked first so an order is never half-received.
  if (next === 'received') {
    // Receiving puts every item into stock as a restock transaction.
    // First check that every product still exists and that the new cost does not
    // exceed its selling price, so we never receive only half of an order.
    for (const item of order.items) {
      const product = await Product.findById(item.product);
      if (!product) throw new HttpError(400, 'A product on this order no longer exists');
      if (item.unitCost > product.unitPrice) {
        throw new HttpError(
          400,
          `${product.name}: order cost (${item.unitCost}) is higher than its selling price (${product.unitPrice}). Update the price first.`
        );
      }
    }
    for (const item of order.items) {
      await recordTransaction({
        productId: item.product,
        type: 'restock',
        quantity: item.quantity,
        unitCost: item.unitCost,
        note: `Received ${order.orderNumber}`,
        purchaseOrder: order._id,
      });
    }
    order.receivedAt = new Date();
  }

  order.status = next;
  await order.save();

  await order.populate(POPULATE);
  res.status(200).json(order);
});

// REQUIREMENT [Core Req 2 - REST API]: delete (200 / 404) - ordered and received orders are protected (400).
// DELETE /api/purchase-orders/:id - only drafts and cancelled orders
router.delete('/:id', async (req, res) => {
  const order = await PurchaseOrder.findById(req.params.id);
  if (!order) throw new HttpError(404, 'Purchase order not found');
  if (order.status === 'ordered') {
    throw new HttpError(400, 'This order was already sent to the supplier. Cancel it first.');
  }
  if (order.status === 'received') {
    throw new HttpError(400, 'Received orders are part of your stock history and cannot be deleted');
  }

  await order.deleteOne();
  res.status(200).json({ message: 'Purchase order deleted' });
});

module.exports = router;
